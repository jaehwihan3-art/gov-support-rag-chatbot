def norm(s):
    return re.sub(r"\s+", "", s)


def main():
    chunks = {}
    for name in ("A1", "A2"):
        chunks[name] = [json.loads(l) for l in open(f"data/chunks/{name}.jsonl", encoding="utf-8")]
    rows, bad = [], 0
    for qid, typ, q, ans, nid, ev in Q:
        found = {}
        for name, cs in chunks.items():
            hit = []
            for e in [x for x in ev.split(" || ") if x]:
                ids = [c["chunk_id"] for c in cs if c["notice_id"] == nid and norm(e) in norm(c["text"])]
                hit.append(ids)
            found[name] = hit
        ok = all(all(h) for h in found.values()) if ev else True
        if not ok:
            bad += 1
            print(f"[근거 못 찾음] {qid} {ev} {found}")
        rows.append({"qid": qid, "type": typ, "question": q, "gold_answer": ans, "notice_id": nid, "evidence": ev,
                     "A1_근거청크": " | ".join(",".join(h) for h in found["A1"]),
                     "A2_근거청크": " | ".join(",".join(h) for h in found["A2"]),
                     "확인(O/X)": "", "수정 메모": ""})
    Path("data/eval").mkdir(parents=True, exist_ok=True)
    with open("data/eval/qa_eval_draft.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    from collections import Counter
    print(Counter(r["type"] for r in rows), "근거 못 찾음:", bad)
    print("저장: data/eval/qa_eval_draft.csv")


if __name__ == "__main__":
    main()
